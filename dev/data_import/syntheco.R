  hou <- qs::qread("dev/data/syntheco/hou.qs")["HH_ID"]
  
  # pop <- read.csv("dev/data/syntheco/syntheco_population.people.csv") |> 
  #   tibble::as_tibble()
  # pop$HH_ID <- paste0("syntheco_hh_", pop$HH_ID)
  # qs::qsave(pop, "dev/data/syntheco/pop.qs")
  pop <- qs::qread("dev/data/syntheco/pop.qs") |> 
    dplyr::select(HH_ID, WT1:YRIMM)
  
  cc.buildr::db_write_prod(pop, table_name = "syntheco_pop",
                           schema = "mtl", primary_key = NULL,
                           index = "HH_ID")
  
  # Modules table -----------------------------------------------------------
  
  modules <-
    scales_variables_modules$modules |>
    add_module(
      id = "syntheco",
      theme = "Demography",
      nav_title = "Synthetic population",
      title_text_title = "Synthetic population",
      title_text_main = paste0(
        "This page displays the synthetic population by showing households at t",
        "heir respective locations and providing details about the individuals ",
        "within these households. The synthetic population data is generated by",
        " the SynthEco lab at McGill University. Academic researchers use synth",
        "etic populations to model and simulate complex social, economic, and e",
        "nvironmental phenomena without compromising individual privacy. This e",
        "nables them to study demographic trends, assess policy impacts, and co",
        "nduct experiments in a controlled, ethical manner, ultimately contribu",
        "ting to more robust and generalizable findings in their respective fie",
        "lds."
      ),
      title_text_extra = paste0(
        ""
      ),
      regions = NULL,
      metadata = TRUE,
      dataset_info = paste0(
        ""
      )
    )
  
  
  # Return ------------------------------------------------------------------
  
  return(list(
    scales = scales_variables_modules$scales,
    variables = variables,
    modules = modules
  ))
  
}
